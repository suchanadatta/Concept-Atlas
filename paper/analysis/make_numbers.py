"""Turn the analysis output into LaTeX macros.

Nothing in the paper is typed by hand that a script could get wrong. Every
figure quoted in the prose is defined here as \\newcommand and used by name, so
re-running the analysis re-writes the paper's numbers with it.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import common as C

OUT = C.PAPER / "generated" / "numbers.tex"


def load(name):
    p = C.DATA / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def fmt(v, dp=None, comma=False):
    if isinstance(v, float):
        return f"{v:.{dp if dp is not None else 2}f}"
    if isinstance(v, int) and comma:
        return f"{v:,}"
    return str(v)


def main():
    lines = ["% generated by analysis/make_numbers.py -- do not edit", ""]
    defs: dict[str, str] = {}

    def put(name, value):
        defs[name] = str(value)

    a1 = load("a1_corpus.json")
    if a1:
        put("NPassages", f"{a1['passages']:,}")
        put("NBooks", a1["books"])
        put("NAuthors", a1["authors"])
        put("YearMin", a1["year_min"])
        put("YearMax", a1["year_max"])
        put("NOcr", f"{a1['by_source'].get('ocr', 0):,}")
        put("NTxt", f"{a1['by_source'].get('txt', 0):,}")
        g = a1["author_groups"]
        for k in ("men", "women"):
            if k in g:
                put(f"N{k.capitalize()}Authors", g[k]["authors"])
                put(f"N{k.capitalize()}Books", g[k]["books"])
                put(f"N{k.capitalize()}Passages", f"{g[k]['passages']:,}")
        put("MedianPassagesPerBook", a1["passages_per_book"]["median"])
        put("MaxPassagesPerBook", f"{a1['passages_per_book']['max']:,}")

    a0 = load("a0_dates.json")
    if a0:
        put("DatedById", a0["dated_by_id"])
        put("DatesRecovered", a0["recovered_from_title_page"])
        put("DatesRefused", a0["rejections"])
        put("StillUndated", a0["still_undated"])
        put("CoverageBefore", f"{100*a0['passage_coverage_before']/a0['passages_total']:.1f}")
        put("CoverageAfter", f"{100*a0['passage_coverage_after']/a0['passages_total']:.1f}")

    a0b = load("a0b_date_validation.json")
    if a0b:
        put("DateCheckN", a0b["title_page_readable"])
        put("DateCheckExact", a0b["exact_match"])
        put("DateCheckWithinOne", a0b["within_one_year"])
        put("DateCheckExactPct", f"{100*a0b['exact_rate']:.0f}")

    a2 = load("a2_graph.json")
    if a2:
        put("NConcepts", a2["nodes"])
        put("NAssertions", f"{a2['assertions']:,}")
        put("NPairs", a2["distinct_pairs"])
        put("AssertionsPerPair", fmt(a2["assertions_per_pair"]))
        put("PairsMulti", a2["pairs_with_multiple_assertions"])
        put("PairsConflicting", a2["pairs_with_conflicting_kinds"])
        put("GraphDensity", f"{a2['density']:.3f}")
        put("MeanDegree", f"{a2['mean_degree']:.1f}")
        put("MaxDegree", a2["max_degree"])
        put("CrossCategoryPct", f"{100*a2['cross_category_share']:.0f}")
        put("Modularity", f"{a2['modularity']:.2f}")
        put("NCommunities", a2["communities"])
        put("RhoImportance", fmt(a2["importance_vs_degree_spearman"]["rho"]))
        put("RhoBookCount", fmt(a2["bookcount_vs_degree_spearman"]["rho"]))
        rel = a2["relations"]
        for k, v in rel.items():
            put("Rel" + "".join(p.capitalize() for p in k.split("_")), v)
        put("TopHub", a2["hubs_by_degree"][0]["label"])
        put("TopHubDegree", a2["hubs_by_degree"][0]["degree"])

    a3 = load("a3_map_vs_vectors.json")
    if a3:
        put("VecConcepts", a3["concepts_with_both_vectors"])
        put("VecPairs", f"{a3['pairs_compared']:,}")
        put("VecLinked", f"{a3['linked_pairs']:,}")
        put("NoteMinSupport", a3["min_support"])
        put("CosLinkedRaw", fmt(a3["usage_uncentred"]["linked"]["mean"], 3))
        put("CosUnlinkedRaw", fmt(a3["usage_uncentred"]["unlinked"]["mean"], 3))
        put("CosLinked", fmt(a3["usage"]["linked"]["mean"], 3))
        put("CosUnlinked", fmt(a3["usage"]["unlinked"]["mean"], 3))
        put("CosLinkedDef", fmt(a3["definition"]["linked"]["mean"], 3))
        put("CosUnlinkedDef", fmt(a3["definition"]["unlinked"]["mean"], 3))
        put("RhoUsageDef", fmt(a3["usage_vs_definition_spearman"]["rho"]))
        for rel, v in a3["by_relation"].items():
            nm = "".join(p.capitalize() for p in rel.split("_"))
            put(f"Cos{nm}", fmt(v["usage_mean"], 3))
            put(f"CosN{nm}", v["n"])

    a4 = load("a4_retrieval.json")
    if a4:
        put("RetrievalK", a4["k"])
        put("RetrievalQueries", a4["queries"])
        put("MeanJaccard", fmt(a4["mean_jaccard"], 3))
        put("MedianJaccard", fmt(a4["median_jaccard"], 3))
        put("MeanBookJaccard", fmt(a4["mean_book_jaccard"], 3))
        rows = a4["all"]
        put("BooksLexMean", f"{sum(r['books_lexical'] for r in rows)/len(rows):.1f}")
        put("BooksSemMean", f"{sum(r['books_semantic'] for r in rows)/len(rows):.1f}")
        put("MostAgreedQuery", a4["most_agreed"][0]["query"])
        put("MostAgreedJ", fmt(a4["most_agreed"][0]["jaccard"], 3))
        put("MostDivergentQuery", a4["most_divergent"][0]["query"])
        put("MostDivergentJ", fmt(a4["most_divergent"][0]["jaccard"], 3))

    a5 = load("a5_diachrony.json")
    if a5:
        put("DiachronicPassages", f"{a5['dated_passages']:,}")
        put("BinYears", a5["bin_years"])
        put("FirstBin", a5["bins"][0])
        put("LastBin", a5["bins"][-1])
        for term, p in a5["profile"].items():
            nm = "".join(w.capitalize() for w in term.replace("-", " ").split())
            put(f"Peak{nm}", p["peak_bin"])
            put(f"PeakRate{nm}", fmt(p["peak_rate"]))
            put(f"First{nm}", fmt(p["first_bin_rate"]))
            put(f"Last{nm}", fmt(p["last_bin_rate"]))

    a6 = load("a6_authorship.json")
    if a6:
        c = a6["confounds"]
        put("WomenBooks", c["women"]["books"])
        put("WomenAuthors", c["women"]["authors"])
        put("WomenPassages", f"{c['women']['passages']:,}")
        put("MenBooks", c["men"]["books"])
        put("MenAuthors", c["men"]["authors"])
        put("MenPassages", f"{c['men']['passages']:,}")
        put("WomenMedianYear", c["women"]["median_year"])
        put("MenMedianYear", c["men"]["median_year"])
        put("TopWomenLean", a6["women_lean"][0]["concept"])
        put("TopWomenLeanRatio", fmt(a6["women_lean"][0]["log2_ratio"]))
        put("TopMenLean", a6["men_lean"][0]["concept"])
        put("TopMenLeanRatio", fmt(abs(a6["men_lean"][0]["log2_ratio"])))

    for k in sorted(defs):
        lines.append(rf"\newcommand{{\{k}}}{{{defs[k]}}}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  wrote {OUT.relative_to(C.REPO)} ({len(defs)} macros)")


if __name__ == "__main__":
    main()
